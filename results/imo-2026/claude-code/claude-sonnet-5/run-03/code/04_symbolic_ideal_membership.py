"""
Certificate 4 (the crux of the proof): an EXACT symbolic (not merely
numerical) verification that

    pow_B(circle AKL) - pow_C(circle AKL) - (AB^2 - AC^2)/2

vanishes identically whenever BK = t and CL = s satisfy the two
quadratics Q_K(t) = 0 and Q_L(s) = 0 from Lemma 3 (equivalently: the
target identity, after clearing the denominator that appears in the
circumcenter formula, lies in the polynomial ideal generated by
Q_K(t) and Q_L(s)).

Setup: circumradius of ABC normalized to 1, B=(0,0), C=(a,0),
A = (2 sin(g) cos(b), 2 sin(g) sin(b)), with b=angle B, g=angle C,
a = 2 sin(pi-b-g) = BC. K,L are placed on their respective x-rays
with free distances t,s (matching build_KL in common.py, transcribed
here symbolically).

Running this script performs the polynomial division and prints the
four coefficients of the fully reduced remainder (a polynomial of
degree <= 1 in each of t and s). Each one simplifies to EXACTLY 0,
which is the rigorous algebraic proof of identity (2) / (7) in the
write-up, given Lemma 2 and Lemma 3.

Expected output: all four coefficients equal to `0`.
"""

import sympy as sp

beta, gamma, x, t, s = sp.symbols('beta gamma x t s', real=True, positive=True)

alpha = sp.pi - beta - gamma
a = 2 * sp.sin(alpha)  # BC, with circumradius(ABC) = 1

Avec = sp.Matrix([2 * sp.sin(gamma) * sp.cos(beta), 2 * sp.sin(gamma) * sp.sin(beta)])
Bvec = sp.Matrix([0, 0])
Cvec = sp.Matrix([a, 0])

K = sp.Matrix([t * sp.cos(beta - x), t * sp.sin(beta - x)])
L = sp.Matrix([a - s * sp.cos(gamma - x), s * sp.sin(gamma - x)])


def circumcenter_num_den(P1, P2, P3):
    """Returns (numerator vector, denominator) with O = numerator/denominator."""
    ax, ay = P1
    bx, by = P2
    cx, cy = P3
    dd = 2 * (ax * (by - cy) + bx * (cy - ay) + cx * (ay - by))
    ux = ((ax**2 + ay**2) * (by - cy) + (bx**2 + by**2) * (cy - ay)
          + (cx**2 + cy**2) * (ay - by))
    uy = ((ax**2 + ay**2) * (cx - bx) + (bx**2 + by**2) * (ax - cx)
          + (cx**2 + cy**2) * (bx - ax))
    return sp.Matrix([ux, uy]), dd


Onum, Dd = circumcenter_num_den((Avec[0], Avec[1]), (K[0], K[1]), (L[0], L[1]))


def dot2(u, v):
    return u[0] * v[0] + u[1] * v[1]


# Target condition pow_B - pow_C = (AB^2-AC^2)/2 is equivalent to
#   (C-B) . (2*O - A) = (|C|^2 - |B|^2)/2
# Multiplying through by Dd (the denominator hidden inside O) clears
# all fractions:
CmB = Cvec - Bvec
lhs = dot2(CmB, 2 * Onum - Avec * Dd) - Dd * (dot2(Cvec, Cvec) - dot2(Bvec, Bvec)) / 2
lhs = sp.expand(lhs)

# Q_K(t) = 0 and Q_L(s) = 0, as derived in Lemma 3 (with R=1 here):
c2t = sp.sin(gamma) * sp.sin(beta + gamma - x)                      # = sin(gamma) sin(alpha+x)
c1t = -(2 * sp.sin(beta + gamma) + sp.sin(beta + gamma - 2 * x)) * sp.sin(gamma) ** 2
c0t = 2 * sp.sin(gamma) ** 2 * sp.sin(beta + gamma) * sp.sin(gamma - x)
qt = c2t * t ** 2 + c1t * t + c0t

c2s = sp.sin(beta) * sp.sin(beta + gamma - x)
c1s = -(2 * sp.sin(beta + gamma) + sp.sin(beta + gamma - 2 * x)) * sp.sin(beta) ** 2
c0s = 2 * sp.sin(beta) ** 2 * sp.sin(beta + gamma) * sp.sin(beta - x)
qs = c2s * s ** 2 + c1s * s + c0s

# Reduce `lhs` modulo qt (in t) and then modulo qs (in s):
expr = lhs
while sp.Poly(sp.expand(expr), t).degree() >= 2:
    _, remainder = sp.div(sp.expand(expr), qt, t)
    expr = sp.expand(remainder)

while sp.Poly(sp.expand(expr), s).degree() >= 2:
    _, remainder = sp.div(sp.expand(expr), qs, s)
    expr = sp.expand(remainder)

final = sp.expand(expr)
finalpoly = sp.Poly(final, t, s)

print("Reduced remainder (degree <= 1 in both t and s):")
for monom, name in [(t * s, "t*s"), (t, "t"), (s, "s"), (1, "1")]:
    coeff = finalpoly.coeff_monomial(monom)
    simplified = sp.simplify(coeff)
    print(f"  coefficient of {name:>3}: {simplified}")

print()
all_zero = all(
    sp.simplify(finalpoly.coeff_monomial(m)) == 0
    for m in (t * s, t, s, 1)
)
print("All four coefficients are exactly zero:", all_zero)
